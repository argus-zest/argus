"""Generate browser response validators from the OpenAPI contract and handler shapes.

Requires PyYAML (also used by local backend tests). No network or AWS operations.
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def generate():
    spec = yaml.safe_load((ROOT / 'contracts/openapi.yaml').read_text())

    def expand(schema):
        if isinstance(schema, list):
            return [expand(item) for item in schema]
        if not isinstance(schema, dict):
            return schema
        if '$ref' in schema:
            ref = schema['$ref']
            directory = 'contracts' if ref.startswith('./schemas/') else 'contracts/schemas'
            return expand(json.loads((ROOT / directory / ref).read_text()))
        return {key: expand(value) for key, value in schema.items()
                if key not in ('description', 'example', 'title')}

    schemas = {
        operation['operationId']: expand(next(
            response['content']['application/json']['schema']
            for code, response in operation['responses'].items() if code.startswith('2')
        ))
        for path in spec['paths'].values() for operation in path.values()
        if isinstance(operation, dict) and 'operationId' in operation
    }
    # Backend emits null for optional analysis/photo fields; components handle it.
    cases = [schemas['createCase'], schemas['listCases']['properties']['cases']['items'],
             schemas['getCase']['properties']['case']]
    for case in cases:
        case['properties']['analysis']['nullable'] = True
    schemas['getCase']['properties']['photo_url']['nullable'] = True

    # OpenAPI leaves these objects unspecified. Shapes come from civic_data,
    # eval/rdd2022_eval.py, and backtest/run_backtest.py, as consumed by the UI.
    string = {'type': 'string'}
    number = {'type': 'number'}
    nullable_number = {'type': 'number', 'nullable': True}
    road = {'type': 'object', 'nullable': True, 'properties': {
        **{key: string for key in ('road_id', 'name', 'road_class', 'provenance')},
        'width_ft': nullable_number,
    }}
    hotspot = schemas['getHotspots']['properties']['hotspots']['items']
    hotspot['properties']['road'] = road
    hotspot['properties']['features'] = {'type': 'object', 'properties': {
        **{key: nullable_number for key in ('elev_m', 'depression_m', 'rel_elev_m', 'news_events_count')},
        'underpass': {'type': 'boolean'},
    }}
    asset = schemas['getAssets']['properties']['assets']['items']
    hotspot['properties']['assets']['items'] = asset
    schemas['resolveLocation']['properties']['road'] = road
    rdd_properties = {
        **{key: string for key in ('dataset', 'model_id', 'run_at', 'level')},
        **{key: number for key in ('precision', 'recall', 'f1', 'n_pos', 'n_neg', 'tp', 'fp', 'fn', 'tn')},
    }
    schemas['getEvalResults']['properties']['rdd2022'] = {
        'type': 'object', 'nullable': True, 'required': list(rdd_properties),
        'properties': rdd_properties,
    }
    schemas['getEvalResults']['properties']['backtest'] = {
        'type': 'object', 'nullable': True, 'properties': {'events': {
            'type': 'array', 'items': {'type': 'object', 'properties': {
                **{key: string for key in ('event_id', 'date', 'description', 'name', 'label')},
                **{key: number for key in ('precision_at_20', 'random_baseline_precision',
                                           'reported_other_count', 'rain_3h_mm',
                                           'rain_prev24h_mm', 'traffic_slowdown')},
                'recall': nullable_number,
                'held_out': {'type': 'boolean'},
                'top20_predicted': {'type': 'array', 'items': string},
                'top_20': {'type': 'array', 'items': {'type': 'object',
                    'required': ['hotspot_id', 'name', 'probability', 'reported_hit'],
                    'properties': {'hotspot_id': string, 'name': string,
                                   'probability': number, 'reported_hit': {'type': 'boolean'}}}},
            }},
        }},
    }
    # claim-fix's object is populated by common.nova.verify_fix.
    schemas['claimFix']['properties']['verification']['properties'] = {
        'hazard_still_present': {'type': 'boolean'},
        'same_location_plausible': {'type': 'boolean', 'nullable': True},
        'confidence': number, 'explanation': string,
        'mock': {'type': 'boolean'}, 'source': string,
    }
    for operation, field in [('analyzeHazard', 'analysis')]:
        schemas[operation]['properties'][field]['properties'].update({
            'mock': {'type': 'boolean'}, 'source': string,
        })
    return ('// Generated by scripts/generate_frontend_schemas.py; do not edit.\n'
            'export const responseSchemas: Record<string, unknown> = '
            + json.dumps(schemas, indent=2) + ';\n')


if __name__ == '__main__':
    (ROOT / 'frontend/src/lib/response-schemas.ts').write_text(generate())
